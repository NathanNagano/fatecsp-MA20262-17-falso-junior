// Consulta fVendas - Código M Oficial
let
    Fonte = Folder.Files("C:\CafeData\dados_brutos\vendas"),
    SoPlanilhas = Table.SelectRows(Fonte, each ([Extension] = ".xlsx") and not Text.StartsWith([Name], "~$")),
    LeituraCustom = Table.AddColumn(SoPlanilhas, "Dados", each fnLerVendas([Content])),
    ExpandirColunas = Table.ExpandTableColumn(LeituraCustom, "Dados", 
        {"Linha_Origem", "ID_Cupom", "Data", "Hora", "Filial", "Produto", "Categoria", "Quantidade", "Valor_Unit", "Desconto", "Pagamento", "Canal"}),
    SemBrancos = Table.SelectRows(ExpandirColunas, each [ID_Cupom] <> null or [Produto] <> null),
    SemDuplicatas1 = Table.Distinct(SemBrancos, {"ID_Cupom", "Produto", "Hora"}),
    TratarDatas = Table.AddColumn(SemDuplicatas1, "Data_Trat", each fnData([Data]), type date),
    NoPeriodo = Table.SelectRows(TratarDatas, each [Data_Trat] >= #date(2026, 1, 1) and [Data_Trat] <= #date(2026, 6, 30)),
    SemHoraInvalida = Table.SelectRows(NoPeriodo, each [Hora] <> null),
    TiposPtBR = Table.TransformColumnTypes(SemHoraInvalida,
        {{"Quantidade", Int64.Type}, {"Valor_Unit", type number}, {"Desconto", type number}}, "pt-BR"),
    QtdEValorValidos = Table.SelectRows(TiposPtBR, each [Quantidade] > 0 and [Valor_Unit] <> null),
    TextosAparados = Table.TransformColumns(QtdEValorValidos,
        {{"Filial", Text.Trim, type text}, {"Produto", Text.Trim, type text}, {"Categoria", Text.Trim, type text}}),
    PrimeiraMaiuscula = Table.TransformColumns(TextosAparados,
        {{"Produto", Text.Proper, type text}, {"Categoria", Text.Proper, type text}}),
    MesclaFilial = Table.NestedJoin(PrimeiraMaiuscula, {"Filial"}, Tab_DePara_Filial, {"Nome_Origem"}, "CadFilial", JoinKind.LeftOuter),
    ExpandeFilial = Table.ExpandTableColumn(MesclaFilial, "CadFilial", {"Cod_Filial"}),
    MesclaProduto = Table.NestedJoin(ExpandeFilial, {"Produto"}, Tab_Produtos, {"Produto"}, "CadProd", JoinKind.LeftOuter),
    ExpandeProduto = Table.ExpandTableColumn(MesclaProduto, "CadProd", {"Cod"}),
    RenomeiaCodProd = Table.RenameColumns(ExpandeProduto, {{"Cod", "Cod_Produto"}}),
    SemNulosCad = Table.SelectRows(RenomeiaCodProd, each [Cod_Filial] <> null and [Cod_Produto] <> null),
    SemDuplicatas2 = Table.Distinct(SemNulosCad, {"ID_Cupom", "Cod_Produto", "Hora"}),
    AddValorBruto = Table.AddColumn(SemDuplicatas2, "Valor_Bruto", each Number.Round([Quantidade] * [Valor_Unit], 2), type number),
    AddValorLiquido = Table.AddColumn(AddValorBruto, "Valor_Liquido", each Number.Round([Valor_Bruto] - [Desconto], 2), type number),
    ColunasFinais = Table.SelectColumns(AddValorLiquido, 
        {"Name", "Linha_Origem", "ID_Cupom", "Data_Trat", "Hora", "Cod_Filial", "Cod_Produto", "Quantidade", "Valor_Unit", "Desconto", "Valor_Bruto", "Valor_Liquido", "Pagamento", "Canal"}),
    RenomeiaColunas = Table.RenameColumns(ColunasFinais, {{"Name", "Arquivo_Origem"}, {"Data_Trat", "Data"}})
in
    RenomeiaColunas
